"""Generate distributable deterministic audio; these signals are not a quality benchmark."""
import hashlib
import json
from pathlib import Path
import numpy as np
import soundfile as sf

ROOT = Path(__file__).resolve().parents[1]


def main():
    target = ROOT / 'data/generated'; target.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(9482)
    rate = 44100; frames = 358533
    t = np.arange(frames) / rate
    envelope = (0.5 + 0.5*np.sin(2*np.pi*0.7*t))**2
    tonal = 0.15*envelope*(np.sin(2*np.pi*220*t)+0.4*np.sin(2*np.pi*440*t))
    beat = np.exp(-((t % 0.5)*35))
    percussion = 0.07*beat*rng.standard_normal(frames)
    mix = np.stack([tonal+percussion+0.1*np.sin(2*np.pi*523.25*t),
                    tonal-percussion+0.1*np.sin(2*np.pi*659.25*t)], axis=1).astype(np.float32)
    files = [('stereo-8.13s.wav', mix, rate),
             ('mono-48k-1s.wav', (0.2*np.sin(2*np.pi*440*np.arange(48000)/48000)).astype(np.float32), 48000)]
    records = []
    for name, audio, sample_rate in files:
        path = target / name; sf.write(path, audio, sample_rate, subtype='FLOAT')
        records.append(dict(file=name, sample_rate=sample_rate, frames=len(audio),
                            sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                            license='Apache-2.0 (generated by this project)', purpose='execution/integrity, not separation quality'))
    (ROOT / 'fixtures/generated-manifest.json').write_text(json.dumps(records, indent=2)+'\n')
    print(target)


if __name__ == '__main__':
    main()
